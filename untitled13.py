# كود تطبيق محاكاة مدارات الكواكب
import streamlit as st
import matplotlib.pyplot as plt
import numpy as np

# عنوان واجهة تطبيق محاكاة حركة الكواكب وقوانين كبلر
st.title("واجهة تطبيق محاكاة حركة الكواكب وقوانين كبلر")
st.markdown("استخدم الأشرطة أدناه لتعديل المعلمات وعرض النتائج الفورية.")

# كما في نموذجك تماماً (Sliders)
e = st.slider("معامل الاختلاف المركزي (e)", min_value=0.0, max_value=0.9, value=0.0167, step=0.01)
a = st.slider("المحور الأكبر (a)", min_value=0.1, max_value=2.0, value=1.0, step=0.1)

# قسم عرض النتيجة والرسم البياني للهندسة الإهليلجية
st.header("Planetary Orbital Simulation Results")

# حسابات هندسية مبسطة للمدار الإهليلجي بناءً على المعادلة القطبية
theta = np.linspace(0, 2 * np.pi, 100)
r = (a * (1 - e**2)) / (1 + e * np.cos(theta))

# تحويل الإحداثيات القطبية إلى ديكارتية للرسم
x = r * np.cos(theta)
y = r * np.sin(theta)

# استخدام Matplotlib لإنشاء الرسم
fig, ax = plt.subplots(figsize=(6, 6))
ax.plot(x, y, label="مدار الكوكب", color="blue")
ax.scatter([0], [0], color="orange", s=100, label="الشمس")
ax.scatter([x[0]], [y[0]], color="red", s=50, label="الكوكب")

ax.set_xlabel("X Position (AU)")
ax.set_ylabel("Y Position (AU)")
ax.legend(loc="upper right")
ax.grid(True)

# عرض الرسم في Streamlit
st.pyplot(fig)